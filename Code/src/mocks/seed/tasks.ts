export function buildTasks(c: SeedClock): {
  tasks: TaskRecord[];
  comments: Comment[];
  activity: ActivityEvent[];
} {
  const activity: ActivityEvent[] = [];
  const tasks: TaskRecord[] = TASKS.map((t, i) => {
    const createdDaysAgo = Math.max(3, (t.due ?? 10) < 0 ? 12 : 6 + (i % 9));
    const createdAt = c.at(-createdDaysAgo, 9 + (i % 7));
    const createdById = t.createdBy ?? t.assignee ?? 'u_dana';
    const completedAt = t.status === 'done' ? c.at(-(t.doneAgo ?? 1), 15) : null;
    activity.push({
      id: `ev_${t.id}_created`,
      taskId: t.id,
      actorId: createdById,
      kind: 'created',
      from: null,
      to: null,
      createdAt,
    });
    if (t.status !== 'todo') {
      activity.push({
        id: `ev_${t.id}_status`,
        taskId: t.id,
        actorId: t.assignee ?? createdById,
        kind: 'status',
        from: 'todo',
        to: t.status,
        createdAt: completedAt ?? c.at(-Math.min(createdDaysAgo - 1, 2), 11),
      });
    }
    return {
      id: t.id,
      title: t.title,
      description: t.description ?? '',
      status: t.status,
      priority: t.priority,
      assigneeId: t.assignee,
      teamId: t.team,
      projectId: t.project,
      dueDate: t.due === null ? null : c.day(t.due),
      labels: t.labels ?? [],
      fileIds: t.files ?? [],
      createdById,
      createdAt,
      updatedAt: completedAt ?? c.at(-1, 16),
      completedAt,
      deletedAt: null,
    };
  });

  const comments: Comment[] = COMMENTS.map(([taskId, authorId, daysAgo, body], i) => ({
    id: `cm_${i + 1}`,
    taskId,
    authorId,
    body,
    // Comments from "today" are minutes to hours old, never later than the moment of seeding.
    createdAt:
      daysAgo === 0 ? c.ago(30 + (COMMENTS.length - i) * 12) : c.at(-daysAgo, 14, 10 + i * 3),
  }));

  return { tasks, comments, activity };
}
