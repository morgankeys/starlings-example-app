// `tokens`: unpack Figma variables exports and regenerate src/styles/tokens.generated.css.
//
// 1. Unpack: every `<name>.zip` in Docs/Design system/Figma tokens/ expands into
//    unpacked/<name>/ (one folder per collection: several exports share file names).
// 2. Build: read the unpacked JSON and write the token CSS. The base mode goes on :root,
//    dark modes on [data-theme='dark'] and on prefers-color-scheme: dark.
//
// The color transform must keep alpha: Figma's `hex` is RGB only, opacity is in `alpha`.
// check-alpha.mjs guards this in `build`.
import fs from 'node:fs';
import path from 'node:path';
import { unzipSync } from 'fflate';
import {
  GENERATED_CSS,
  TOKENS_DIR,
  UNPACKED_DIR,
  isDarkMode,
  readSources,
  rgbFrom,
  varName,
} from './lib/tokens-source.mjs';

function unpack() {
  if (!fs.existsSync(TOKENS_DIR)) return;
  for (const zip of fs.readdirSync(TOKENS_DIR).filter((f) => f.endsWith('.zip'))) {
    const target = path.join(UNPACKED_DIR, zip.replace(/\.zip$/, ''));
    const entries = unzipSync(fs.readFileSync(path.join(TOKENS_DIR, zip)));
    for (const [name, bytes] of Object.entries(entries)) {
      if (name.endsWith('/')) continue;
      const out = path.join(target, path.basename(name));
      fs.mkdirSync(path.dirname(out), { recursive: true });
      fs.writeFileSync(out, bytes);
    }
    console.log(`tokens: unpacked ${zip} → unpacked/${path.basename(target)}/`);
  }
}

export function colorValue(value) {
  const alpha = value.alpha ?? 1;
  if (alpha >= 1) return value.hex.toLowerCase();
  const [r, g, b] = rgbFrom(value);
  return `rgb(${r} ${g} ${b} / ${Number(alpha.toFixed(3))})`;
}

function numberValue(token) {
  const p = token.path.join('/');
  if (/^font\/(weight|line-height)\//.test(p)) return String(token.value);
  if (/^font\/letter-spacing\//.test(p)) return token.value === 0 ? '0' : `${token.value}em`;
  if (/^duration\//.test(p)) return `${token.value}ms`;
  return token.value === 0 ? '0' : `${token.value}px`;
}

function cssValue(token) {
  if (token.type === 'color') return colorValue(token.value);
  if (token.type === 'number') return numberValue(token);
  return String(token.value);
}

function build() {
  const sources = readSources();
  if (sources.length === 0) {
    console.error('tokens: no token JSON found under', UNPACKED_DIR);
    process.exit(1);
  }
  const base = new Map();
  const dark = new Map();
  for (const source of sources) {
    const target = isDarkMode(source.mode) ? dark : base;
    for (const token of source.tokens) target.set(varName(token), cssValue(token));
  }
  const block = (map) =>
    [...map.entries()].map(([name, value]) => `  ${name}: ${value};`).join('\n');

  const css = `/* GENERATED by Code/scripts/tokens.mjs from Docs/Design system/Figma tokens/.
 * Do not edit by hand: change the token source or the transform, then run \`npm run tokens\`. */

:root {
  color-scheme: light;
${block(base)}
}

:root[data-theme='dark'] {
  color-scheme: dark;
${block(dark)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${block(dark).replace(/^ {2}/gm, '    ')}
  }
}
`;
  const previous = fs.existsSync(GENERATED_CSS) ? fs.readFileSync(GENERATED_CSS, 'utf8') : '';
  if (previous !== css) {
    fs.writeFileSync(GENERATED_CSS, css);
    console.log(
      `tokens: wrote ${path.relative(process.cwd(), GENERATED_CSS)} (${base.size} base, ${dark.size} dark)`,
    );
  } else {
    console.log('tokens: up to date');
  }
}

unpack();
build();
