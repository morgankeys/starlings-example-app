// `tokens`: unpack Figma variables exports and regenerate src/styles/tokens.generated.css.
//
// 1. Unpack: every `<name>.zip` in Docs/Design system/Figma tokens/ expands into
//    unpacked/<name>/ (one folder per collection: several exports share file names).
// 2. Build: read the unpacked JSON and write the token CSS. The base mode goes on :root,
//    dark modes on [data-theme='dark'] and on prefers-color-scheme: dark.
//
// 3. Compose: `elevation/<level>/{x,y,blur,spread}` numbers become one box-shadow token,
//    `--bd-elevation-<level>`, colored by `shadow/<level minus its size suffix>` (so
//    `overlay-sm` uses `--bd-color-shadow-overlay`). Missing x and spread default to 0.
// 4. Type: Docs/Design system/type-styles.json becomes one class per style in
//    src/styles/type.generated.css, built only from Primitives font tokens.
//
// The color transform must keep alpha: Figma's `hex` is RGB only, opacity is in `alpha`.
// check-alpha.mjs guards this in `build`.
import fs from 'node:fs';
import path from 'node:path';
import { unzipSync } from 'fflate';
import {
  GENERATED_CSS,
  TOKENS_DIR,
  TYPE_CSS,
  TYPE_STYLES,
  UNPACKED_DIR,
  isDarkMode,
  readSources,
  rgbFrom,
  varName,
} from './lib/tokens-source.mjs';

function unpack() {
  if (!fs.existsSync(TOKENS_DIR)) return;
  for (const zip of fs.readdirSync(TOKENS_DIR).filter((f) => f.endsWith('.zip'))) {
    const target = path.join(UNPACKED_DIR, zip.replace(/\.zip$/, ''));
    const entries = unzipSync(fs.readFileSync(path.join(TOKENS_DIR, zip)));
    for (const [name, bytes] of Object.entries(entries)) {
      if (name.endsWith('/')) continue;
      const out = path.join(target, path.basename(name));
      fs.mkdirSync(path.dirname(out), { recursive: true });
      fs.writeFileSync(out, bytes);
    }
    console.log(`tokens: unpacked ${zip} → unpacked/${path.basename(target)}/`);
  }
}

export function colorValue(value) {
  const alpha = value.alpha ?? 1;
  if (alpha >= 1) return value.hex.toLowerCase();
  const [r, g, b] = rgbFrom(value);
  return `rgb(${r} ${g} ${b} / ${Number(alpha.toFixed(3))})`;
}

function numberValue(token) {
  const p = token.path.join('/');
  // Figma exports FLOAT values with binary precision noise. Six decimal places retain
  // useful typography precision while producing stable CSS for the original values.
  const typographyValue = Number(token.value.toFixed(6));
  if (/^font\/weight\//.test(p)) return String(token.value);
  if (/^font\/line-height\//.test(p)) return String(typographyValue);
  if (/^font\/letter-spacing\//.test(p)) {
    return typographyValue === 0 ? '0' : `${typographyValue}em`;
  }
  if (/^duration\//.test(p)) return `${token.value}ms`;
  return token.value === 0 ? '0' : `${token.value}px`;
}

function cssValue(token) {
  if (token.type === 'color') return colorValue(token.value);
  if (token.type === 'number') return numberValue(token);
  return String(token.value);
}

function build() {
  const sources = readSources();
  if (sources.length === 0) {
    console.error('tokens: no token JSON found under', UNPACKED_DIR);
    process.exit(1);
  }
  const base = new Map();
  const dark = new Map();
  for (const source of sources) {
    const target = isDarkMode(source.mode) ? dark : base;
    for (const token of source.tokens) target.set(varName(token), cssValue(token));
  }
  composeElevation(sources, base, dark);
  const block = (map) =>
    [...map.entries()].map(([name, value]) => `  ${name}: ${value};`).join('\n');

  const css = `/* GENERATED by Code/scripts/tokens.mjs from Docs/Design system/Figma tokens/.
 * Do not edit by hand: change the token source or the transform, then run \`npm run tokens\`. */

:root {
  color-scheme: light;
${block(base)}
}

:root[data-theme='dark'] {
  color-scheme: dark;
${block(dark)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${block(dark).replace(/^ {2}/gm, '    ')}
  }
}
`;
  writeIfChanged(GENERATED_CSS, css, `${base.size} base, ${dark.size} dark`);
  buildTypeStyles(base);
}

function writeIfChanged(file, content, note) {
  const previous = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  const rel = path.relative(process.cwd(), file);
  if (previous === content) {
    console.log(`tokens: ${rel} up to date`);
    return;
  }
  fs.writeFileSync(file, content);
  console.log(`tokens: wrote ${rel} (${note})`);
}

const fail = (message) => {
  console.error(`tokens: ${message}`);
  process.exit(1);
};

/** Combine `elevation/<level>/<part>` numbers into `--bd-elevation-<level>` box-shadows. */
function composeElevation(sources, base, dark) {
  const levels = new Map();
  for (const source of sources) {
    for (const token of source.tokens) {
      if (token.path[0] !== 'elevation' || token.type !== 'number') continue;
      if (token.path.length !== 3)
        fail(`expected elevation/<level>/<part>: ${token.path.join('/')}`);
      const [, level, part] = token.path;
      if (!['x', 'y', 'blur', 'spread'].includes(part)) {
        fail(`unknown elevation part "${part}" in ${token.path.join('/')}`);
      }
      if (!levels.has(level)) levels.set(level, new Map());
      levels.get(level).set(part, varName(token));
    }
  }
  for (const [level, parts] of levels) {
    for (const part of ['y', 'blur']) {
      if (!parts.has(part)) fail(`elevation/${level} is missing its ${part}`);
    }
    const color = `--bd-color-shadow-${level.replace(/-[^-]+$/, '')}`;
    if (!base.has(color) || !dark.has(color)) {
      fail(`elevation/${level} needs the color token ${color} in light and dark`);
    }
    const part = (name) => (parts.has(name) ? `var(${parts.get(name)})` : '0');
    base.set(
      `--bd-elevation-${level}`,
      `${part('x')} ${part('y')} ${part('blur')} ${part('spread')} var(${color})`,
    );
  }
}

const TYPE_FIELDS = [
  ['family', 'font-family', 'font-family'],
  ['size', 'font-size', 'font-size'],
  ['weight', 'font-weight', 'font-weight'],
  ['lineHeight', 'line-height', 'font-line-height'],
  ['letterSpacing', 'letter-spacing', 'font-letter-spacing'],
];

/** One class per reviewed type style, every value a Primitives token. */
function buildTypeStyles(base) {
  if (!fs.existsSync(TYPE_STYLES)) return;
  const { styles } = JSON.parse(fs.readFileSync(TYPE_STYLES, 'utf8'));
  const rules = [];
  for (const [name, style] of Object.entries(styles)) {
    if (!/^[a-z0-9]+(\/[a-z0-9-]+)?$/.test(name)) fail(`bad type style name "${name}"`);
    const decls = [];
    for (const [field, prop, group] of TYPE_FIELDS) {
      if (!style[field]) fail(`type style ${name} is missing ${field}`);
      const token = `--bd-${group}-${style[field]}`;
      if (!base.has(token)) fail(`type style ${name}: ${token} is not a token`);
      decls.push(`  ${prop}: var(${token});`);
    }
    if (style.textTransform) decls.push(`  text-transform: ${style.textTransform};`);
    rules.push(
      `/* ${name}: ${style.usage} */\n.bd-type-${name.replace('/', '-')} {\n${decls.join('\n')}\n}`,
    );
  }
  const css = `/* GENERATED by Code/scripts/tokens.mjs from Docs/Design system/type-styles.json.
 * Do not edit by hand: change the type-style source, then run \`npm run tokens\`. */

${rules.join('\n\n')}
`;
  writeIfChanged(TYPE_CSS, css, `${rules.length} type styles`);
}

unpack();
build();
